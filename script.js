const supportedLanguages = Object.keys(translations);
const languageButtons = document.querySelectorAll("[data-language]");
const metaDescription = document.querySelector('meta[name="description"]');

function normalizeLanguage(value) {
  const language = value?.toLowerCase().split("-")[0];
  return supportedLanguages.includes(language) ? language : null;
}

function selectInitialLanguage() {
  const queryLanguage = normalizeLanguage(new URLSearchParams(window.location.search).get("lang"));
  const savedLanguage = normalizeLanguage(window.localStorage.getItem("migakisoft-language"));
  const browserLanguage = normalizeLanguage(window.navigator.language);
  return queryLanguage || savedLanguage || browserLanguage || "en";
}

function setLanguage(language) {
  const selectedLanguage = normalizeLanguage(language) || "en";
  const copy = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  document.title = copy.documentTitle;
  metaDescription.setAttribute("content", copy.metaDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) element.textContent = copy[key];
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (copy[key]) element.setAttribute("aria-label", copy[key]);
  });

  document.querySelectorAll("[data-contact-email]").forEach((element) => {
    element.href = `mailto:info@migakisoft.com?subject=${encodeURIComponent(copy.contactSubject)}`;
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === selectedLanguage));
  });

  window.localStorage.setItem("migakisoft-language", selectedLanguage);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

document.getElementById("current-year").textContent = new Date().getFullYear();
setLanguage(selectInitialLanguage());
